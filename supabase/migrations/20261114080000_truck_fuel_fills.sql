-- Historical truck fuel fills. Deliveries between fills use that fill's
-- price_per_gallon for operating fuel cost (with truck MPG).

CREATE TABLE IF NOT EXISTS public.truck_fuel_fills (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filled_at timestamptz NOT NULL,
  gallons numeric(10, 3) NOT NULL,
  total_amount numeric(10, 2) NOT NULL,
  price_per_gallon numeric(10, 4) NOT NULL,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT truck_fuel_fills_gallons_check CHECK (gallons > 0),
  CONSTRAINT truck_fuel_fills_total_amount_check CHECK (total_amount >= 0),
  CONSTRAINT truck_fuel_fills_price_check CHECK (price_per_gallon >= 0)
);
CREATE INDEX IF NOT EXISTS truck_fuel_fills_filled_at_idx
  ON public.truck_fuel_fills (filled_at);
COMMENT ON TABLE public.truck_fuel_fills IS
  'Pump fills with gallons and total paid. Trips from filled_at until the next fill use this price_per_gallon for fuel cost.';
COMMENT ON COLUMN public.truck_fuel_fills.price_per_gallon IS
  'Stored as total_amount / gallons at save time for audit stability.';
ALTER TABLE public.truck_fuel_fills ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS truck_fuel_fills_admin_all ON public.truck_fuel_fills;
CREATE POLICY truck_fuel_fills_admin_all
  ON public.truck_fuel_fills
  FOR ALL
  USING (public.is_admin() OR auth.role() = 'service_role')
  WITH CHECK (public.is_admin() OR auth.role() = 'service_role');
GRANT SELECT, INSERT, UPDATE, DELETE ON public.truck_fuel_fills TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.truck_fuel_fills_id_seq TO authenticated, service_role;
