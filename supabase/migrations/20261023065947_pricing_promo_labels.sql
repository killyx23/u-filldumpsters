-- Reusable deal labels for service pricing. A service shows its label on the
-- customer price only when show_promo_label is on and a label is chosen.

CREATE TABLE IF NOT EXISTS public.pricing_promo_labels (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pricing_promo_labels_label_key UNIQUE (label)
);

COMMENT ON TABLE public.pricing_promo_labels IS
  'Deal labels an admin can attach to any service price and reuse.';

ALTER TABLE public.services
  ADD COLUMN IF NOT EXISTS promo_label_id bigint REFERENCES public.pricing_promo_labels (id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS show_promo_label boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.services.show_promo_label IS
  'When true and promo_label_id is set, customers see the label next to this service price.';

INSERT INTO public.pricing_promo_labels (label)
VALUES
  ('Winter sale'),
  ('Off-season'),
  ('Limited pricing'),
  ('Holiday deal'),
  ('Black Friday'),
  ('Spring sale'),
  ('Summer sale'),
  ('Fall sale')
ON CONFLICT (label) DO NOTHING;

ALTER TABLE public.pricing_promo_labels ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public read pricing promo labels" ON public.pricing_promo_labels;
CREATE POLICY "public read pricing promo labels"
  ON public.pricing_promo_labels
  FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "admin write pricing promo labels" ON public.pricing_promo_labels;
CREATE POLICY "admin write pricing promo labels"
  ON public.pricing_promo_labels
  FOR ALL
  USING ((auth.role() = 'service_role') OR public.is_admin())
  WITH CHECK ((auth.role() = 'service_role') OR public.is_admin());

GRANT SELECT ON public.pricing_promo_labels TO anon, authenticated, service_role;
GRANT INSERT, UPDATE, DELETE ON public.pricing_promo_labels TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.pricing_promo_labels_id_seq TO authenticated, service_role;

-- Recreate so services.* includes the new columns. CREATE OR REPLACE cannot
-- insert columns ahead of the group columns already in this view.
DROP VIEW IF EXISTS public.services_resolved;
CREATE VIEW public.services_resolved AS
SELECT
  s.*,
  g.slug AS group_slug,
  g.name AS group_name,
  g.description AS group_description,
  g.display_order AS group_display_order,
  coalesce(s.slot_interval_minutes, (g.defaults->>'slot_interval_minutes')::integer) AS resolved_slot_interval_minutes,
  coalesce(s.price_unit, g.defaults->>'price_unit') AS resolved_price_unit,
  coalesce(s.homepage_price_unit, g.defaults->>'homepage_price_unit') AS resolved_homepage_price_unit,
  coalesce(s.homepage_highlight, g.defaults->>'homepage_highlight') AS resolved_homepage_highlight,
  pl.label AS promo_label
FROM public.services s
LEFT JOIN public.service_groups g ON g.id = s.group_id
LEFT JOIN public.pricing_promo_labels pl ON pl.id = s.promo_label_id;

COMMENT ON VIEW public.services_resolved IS
  'Services left-joined to their group and optional pricing promo label.';

GRANT SELECT ON public.services_resolved TO anon, authenticated, service_role;
