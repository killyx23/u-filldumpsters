-- Per-trip truck odometer / actual miles log for deliveries and other truck use.
-- Compares truck miles to GPS/route; audit note required when they differ.
-- Sums feed fuel-fill MPG windows when present.

CREATE TABLE IF NOT EXISTS public.truck_mileage_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL,
  odometer_start numeric(12, 1),
  odometer_end numeric(12, 1),
  truck_miles numeric(10, 2) NOT NULL,
  gps_miles numeric(10, 2),
  variance_miles numeric(10, 2),
  booking_id bigint REFERENCES public.bookings (id) ON DELETE SET NULL,
  purpose text NOT NULL DEFAULT 'other',
  audit_note text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT truck_mileage_entries_purpose_check
    CHECK (purpose IN ('delivery', 'pickup_haul', 'other')),
  CONSTRAINT truck_mileage_entries_truck_miles_check CHECK (truck_miles >= 0),
  CONSTRAINT truck_mileage_entries_gps_miles_check CHECK (gps_miles IS NULL OR gps_miles >= 0),
  CONSTRAINT truck_mileage_entries_odometer_check
    CHECK (
      odometer_start IS NULL
      OR odometer_end IS NULL
      OR odometer_end >= odometer_start
    )
);
CREATE INDEX IF NOT EXISTS truck_mileage_entries_occurred_at_idx
  ON public.truck_mileage_entries (occurred_at);
CREATE INDEX IF NOT EXISTS truck_mileage_entries_booking_id_idx
  ON public.truck_mileage_entries (booking_id);
COMMENT ON TABLE public.truck_mileage_entries IS
  'Per-trip truck miles (odometer or entered). Historical audit log; feeds MPG between fuel fills.';
COMMENT ON COLUMN public.truck_mileage_entries.variance_miles IS
  'truck_miles − gps_miles when GPS is present; null when gps_miles is null.';
COMMENT ON COLUMN public.truck_mileage_entries.audit_note IS
  'Required when variance_miles is not zero.';
ALTER TABLE public.truck_mileage_entries ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS truck_mileage_entries_admin_all ON public.truck_mileage_entries;
CREATE POLICY truck_mileage_entries_admin_all
  ON public.truck_mileage_entries
  FOR ALL
  USING (public.is_admin() OR auth.role() = 'service_role')
  WITH CHECK (public.is_admin() OR auth.role() = 'service_role');
GRANT SELECT, INSERT, UPDATE, DELETE ON public.truck_mileage_entries TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.truck_mileage_entries_id_seq TO authenticated, service_role;
